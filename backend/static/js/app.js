// Multimodal Attendance & Engagement Agent Frontend Controller

let attentionChart = null;
let emotionChart = null;
let audioService = null;
let sessionSeconds = 0;

document.addEventListener("DOMContentLoaded", () => {
  setupNavigation();
  setupTimer();
  startLiveMonitoring();
  initAudioCapture();
  loadTeacherProfile();
  loadSessionAnalytics();
});

function setupNavigation() {
  const tabs = document.querySelectorAll(".nav-tab");
  tabs.forEach(tab => {
    tab.addEventListener("click", () => {
      tabs.forEach(t => t.classList.remove("active"));
      tab.classList.add("active");

      const target = tab.getAttribute("data-tab");
      document.querySelectorAll(".tab-pane").forEach(pane => pane.classList.remove("active"));
      const activePane = document.getElementById(target);
      if (activePane) activePane.classList.add("active");

      if (target === "analytics") {
        setTimeout(loadSessionAnalytics, 100);
      } else if (target === "teacher") {
        loadTeacherProfile();
      }
    });
  });
}

function setupTimer() {
  const timerElem = document.getElementById("sessionTimer");
  setInterval(() => {
    sessionSeconds++;
    const mins = String(Math.floor(sessionSeconds / 60)).padStart(2, "0");
    const secs = String(sessionSeconds % 60).padStart(2, "0");
    if (timerElem) timerElem.textContent = `${mins}:${secs}`;
  }, 1000);
}

function initAudioCapture() {
  audioService = new window.AudioCaptureService((metrics) => {
    updateAudioHUD(metrics);
  });
  audioService.start();
}

function updateAudioHUD(metrics) {
  const dbValueElem = document.getElementById("audioDbValue");
  const meterBar = document.getElementById("audioMeterBar");
  const patternElem = document.getElementById("audioPattern");

  if (metrics && dbValueElem && meterBar) {
    const db = metrics.decibels || -30;
    dbValueElem.textContent = `${db} dB`;
    const percentage = Math.min(100, Math.max(5, ((db + 60) / 60) * 100));
    meterBar.style.width = `${percentage}%`;
    if (patternElem && metrics.activity_pattern) {
      patternElem.textContent = metrics.activity_pattern;
    }
  }
}

async function startLiveMonitoring() {
  const poll = async () => {
    try {
      const res = await fetch("/api/session/status");
      if (res.ok) {
        const data = await res.json();
        renderLiveMetrics(data);
      }
    } catch (e) {
      console.warn("Polling error:", e);
    }
    setTimeout(poll, 1500);
  };
  poll();
}

function renderLiveMetrics(data) {
  // Stats boxes
  const attElem = document.getElementById("avgAttentionValue");
  const countElem = document.getElementById("participantCount");
  const presentCountElem = document.getElementById("presentCount");

  if (attElem) attElem.textContent = `${data.avg_attention}%`;
  if (countElem) countElem.textContent = data.participant_count || 0;

  // AI Insight
  const insightText = document.getElementById("aiInsightText");
  const insightSource = document.getElementById("aiInsightSource");
  if (data.ai_insight && insightText) {
    insightText.textContent = data.ai_insight.insight;
    if (insightSource) insightSource.textContent = `Generated by: ${data.ai_insight.source}`;
  }

  // AI Suggestions
  const suggestionsList = document.getElementById("aiSuggestionsList");
  if (suggestionsList && data.teaching_suggestions) {
    suggestionsList.innerHTML = data.teaching_suggestions
      .map(s => `<li style="margin-bottom:0.4rem;">💡 ${s}</li>`)
      .join("");
  }

  // Real-time Alerts
  const alertsContainer = document.getElementById("alertsFeed");
  if (alertsContainer && data.recommendations) {
    if (data.recommendations.length === 0) {
      alertsContainer.innerHTML = `<div class="alert-item info">✨ All participants attentive. No issues detected.</div>`;
    } else {
      alertsContainer.innerHTML = data.recommendations.map(r => `
        <div class="alert-item ${r.type}">
          <span>${r.type === 'alert' ? '⚠️' : r.type === 'warning' ? '⚡' : 'ℹ️'}</span>
          <span>${r.message}</span>
        </div>
      `).join("");
    }
  }

  // Attendance Table
  const attendanceTbody = document.getElementById("attendanceTableBody");
  if (attendanceTbody && data.attendance) {
    let presentCount = 0;
    attendanceTbody.innerHTML = data.attendance.map(row => {
      if (row.is_present) presentCount++;
      const isPresent = row.status === "Present";
      return `
        <tr>
          <td><strong>${row.student_id}</strong></td>
          <td>${row.student_name}</td>
          <td>${row.duration_seconds}s</td>
          <td>
            <span class="badge ${isPresent ? 'badge-present' : 'badge-progress'}">
              ${row.status}
            </span>
          </td>
        </tr>
      `;
    }).join("");

    if (presentCountElem) presentCountElem.textContent = `${presentCount} / ${data.attendance.length || 0}`;
  }

  if (data.audio) {
    updateAudioHUD(data.audio);
  }
}

async function loadTeacherProfile() {
  try {
    const res = await fetch("/api/teacher-profile?teacher_id=T101");
    if (!res.ok) return;
    const profile = await res.json();

    document.getElementById("teacherScore").textContent = profile.effectiveness_score;
    document.getElementById("teacherTrend").textContent = `+${profile.trend}% vs last week`;

    // Strengths
    const strengthsList = document.getElementById("teacherStrengths");
    if (strengthsList) {
      strengthsList.innerHTML = profile.strengths.map(s => `<li>🌟 ${s}</li>`).join("");
    }

    // Recommendations
    const recsList = document.getElementById("teacherRecs");
    if (recsList) {
      recsList.innerHTML = profile.recommendations.map(r => `<li>🎯 ${r}</li>`).join("");
    }

    // Class History
    const historyContainer = document.getElementById("classHistoryCards");
    if (historyContainer) {
      historyContainer.innerHTML = profile.class_history.map(c => `
        <div class="stat-box" style="text-align:left;">
          <div style="font-weight:600; font-size:0.9rem;">${c.name}</div>
          <div class="stat-value" style="font-size:1.4rem; color:var(--accent-blue);">${c.engagement}% Avg</div>
        </div>
      `).join("");
    }

    // Student Trends
    const trendsTbody = document.getElementById("studentTrendsBody");
    if (trendsTbody) {
      trendsTbody.innerHTML = profile.student_trends.map(s => {
        const isUp = s.change >= 0;
        return `
          <tr>
            <td><strong>${s.name}</strong></td>
            <td style="color:${isUp ? 'var(--accent-green)' : 'var(--accent-red)'}; font-weight:600;">
              ${isUp ? '+' : ''}${s.change}%
            </td>
            <td>
              <span class="badge ${isUp ? 'badge-present' : 'badge-progress'}">${s.status}</span>
            </td>
          </tr>
        `;
      }).join("");
    }
  } catch (e) {
    console.error("Error loading teacher profile:", e);
  }
}

async function loadSessionAnalytics() {
  try {
    const res = await fetch("/api/analytics?session_id=1");
    if (!res.ok) return;
    const data = await res.json();

    renderAttentionChart(data.timestamps, data.attention_trend);
    renderEmotionChart(data.timestamps, data.emotion_distribution);
  } catch (e) {
    console.error("Error loading analytics:", e);
  }
}

function renderAttentionChart(labels, values) {
  const ctx = document.getElementById("attentionChart");
  if (!ctx) return;

  if (attentionChart) attentionChart.destroy();

  attentionChart = new Chart(ctx, {
    type: "line",
    data: {
      labels: labels,
      datasets: [{
        label: "Average Attention Score (%)",
        data: values,
        borderColor: "#3b82f6",
        backgroundColor: "rgba(59, 130, 246, 0.15)",
        fill: true,
        tension: 0.35,
        borderWidth: 2,
        pointBackgroundColor: "#06b6d4",
        pointRadius: 4
      }]
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: { labels: { color: "#94a3b8" } }
      },
      scales: {
        y: {
          min: 40,
          max: 100,
          ticks: { color: "#94a3b8" },
          grid: { color: "#334155" }
        },
        x: {
          ticks: { color: "#94a3b8" },
          grid: { color: "#1e293b" }
        }
      }
    }
  });
}

function renderEmotionChart(labels, emotionDist) {
  const ctx = document.getElementById("emotionChart");
  if (!ctx) return;

  if (emotionChart) emotionChart.destroy();

  emotionChart = new Chart(ctx, {
    type: "bar",
    data: {
      labels: labels,
      datasets: [
        {
          label: "Attentive",
          data: emotionDist.attentive || [],
          backgroundColor: "#10b981"
        },
        {
          label: "Neutral",
          data: emotionDist.neutral || [],
          backgroundColor: "#3b82f6"
        },
        {
          label: "Distracted",
          data: emotionDist.distracted || [],
          backgroundColor: "#ef4444"
        }
      ]
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: { labels: { color: "#94a3b8" } }
      },
      scales: {
        y: {
          stacked: true,
          ticks: { color: "#94a3b8" },
          grid: { color: "#334155" }
        },
        x: {
          stacked: true,
          ticks: { color: "#94a3b8" },
          grid: { color: "#1e293b" }
        }
      }
    }
  });
}

function exportCsv() {
  window.location.href = "/api/analytics/export-csv?session_id=1";
}

function printReport() {
  window.print();
}

window.exportCsv = exportCsv;
window.printReport = printReport;
